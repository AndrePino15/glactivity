-- Phase 2: workouts, meals and reminder notifications.

-- ---------------------------------------------------------------------------
-- Workouts
-- ---------------------------------------------------------------------------

create type public.workout_kind as enum ('gym', 'home', 'run', 'sport', 'rest');

-- The weekly plan: one row per weekday (0 = Sunday … 6 = Saturday, as in JavaScript).
create table public.workout_plan (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users on delete cascade,
  weekday smallint not null check (weekday between 0 and 6),
  title text not null check (length(trim(title)) > 0),
  kind public.workout_kind not null default 'gym',
  preferred_time time,
  -- Exercises or notes, one per line.
  details text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, weekday)
);

create trigger workout_plan_updated_at before update on public.workout_plan
  for each row execute function public.set_updated_at();

-- What actually happened on a day: done or skipped, and what it ended up being.
create table public.workout_logs (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users on delete cascade,
  day date not null,
  title text not null,
  kind public.workout_kind not null,
  status text not null check (status in ('done', 'skipped')),
  notes text,
  created_at timestamptz not null default now(),
  unique (user_id, day)
);

-- ---------------------------------------------------------------------------
-- Meals
-- ---------------------------------------------------------------------------

create type public.meal_slot as enum ('lunch', 'dinner');

-- Meals you make often, with what to buy for them.
create table public.meals (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users on delete cascade,
  name text not null check (length(trim(name)) > 0),
  ingredients text[] not null default '{}',
  notes text,
  created_at timestamptz not null default now()
);

create index meals_user_idx on public.meals (user_id);

create table public.meal_plan (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users on delete cascade,
  day date not null,
  slot public.meal_slot not null,
  title text not null check (length(trim(title)) > 0),
  meal_id uuid references public.meals on delete set null,
  created_at timestamptz not null default now(),
  unique (user_id, day, slot)
);

create index meal_plan_meal_idx on public.meal_plan (meal_id);

-- ---------------------------------------------------------------------------
-- Reminder notifications
-- ---------------------------------------------------------------------------

-- One row per device that agreed to notifications.
create table public.push_subscriptions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users on delete cascade,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  created_at timestamptz not null default now()
);

create index push_subscriptions_user_idx on public.push_subscriptions (user_id);

-- So each reminder is announced once per occasion, not every time the job runs.
alter table public.reminders add column last_notified_on date;

-- Push keys and the daily job's token live outside the API's reach. The keys
-- are generated by the app on first use; the token is made here and never
-- leaves the database except to the scheduled job.
create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create table private.push_config (
  id boolean primary key default true check (id),
  vapid_public text,
  vapid_private text,
  cron_token uuid not null default gen_random_uuid()
);

insert into private.push_config default values;

-- The public key browsers need to subscribe. Not secret.
create function public.vapid_public_key() returns text
language sql stable security definer set search_path = ''
as $$ select vapid_public from private.push_config $$;

-- Stores the push keys the first time they're generated; later calls keep the first pair.
create function public.init_vapid(public_key text, private_key text) returns text
language plpgsql security definer set search_path = ''
as $$
begin
  update private.push_config
    set vapid_public = public_key, vapid_private = private_key
    where vapid_public is null;
  return (select vapid_public from private.push_config);
end;
$$;

-- Keys for sending a test notification to your own devices.
create function public.my_push_keys() returns jsonb
language sql stable security definer set search_path = ''
as $$
  select jsonb_build_object('public', vapid_public, 'private', vapid_private)
  from private.push_config
  where (select auth.uid()) is not null;
$$;

create function private.check_token(token uuid) returns void
language plpgsql stable set search_path = ''
as $$
begin
  if not exists (select 1 from private.push_config where cron_token = token) then
    raise exception 'invalid token' using errcode = '42501';
  end if;
end;
$$;

-- Everything the daily job needs, only for the holder of the token.
create function public.push_batch(token uuid) returns jsonb
language plpgsql stable security definer set search_path = ''
as $$
begin
  perform private.check_token(token);
  return jsonb_build_object(
    'keys', (select jsonb_build_object('public', vapid_public, 'private', vapid_private) from private.push_config),
    'reminders', coalesce((select jsonb_agg(to_jsonb(r)) from public.reminders r where not r.archived), '[]'::jsonb),
    'subscriptions', coalesce((select jsonb_agg(to_jsonb(s)) from public.push_subscriptions s), '[]'::jsonb)
  );
end;
$$;

create function public.mark_notified(token uuid, reminder_ids uuid[], on_day date) returns void
language plpgsql security definer set search_path = ''
as $$
begin
  perform private.check_token(token);
  update public.reminders set last_notified_on = on_day where id = any (reminder_ids);
end;
$$;

-- Devices that unsubscribed or were reset answer "gone"; forget them.
create function public.forget_subscription(token uuid, gone_endpoint text) returns void
language plpgsql security definer set search_path = ''
as $$
begin
  perform private.check_token(token);
  delete from public.push_subscriptions where endpoint = gone_endpoint;
end;
$$;

revoke execute on function public.vapid_public_key() from public, anon;
revoke execute on function public.init_vapid(text, text) from public, anon;
revoke execute on function public.my_push_keys() from public, anon;
revoke execute on function public.push_batch(uuid) from public, authenticated;
revoke execute on function public.mark_notified(uuid, uuid[], date) from public, authenticated;
revoke execute on function public.forget_subscription(uuid, text) from public, authenticated;
revoke execute on function private.check_token(uuid) from public, anon, authenticated;

grant execute on function public.vapid_public_key() to authenticated;
grant execute on function public.init_vapid(text, text) to authenticated;
grant execute on function public.my_push_keys() to authenticated;
-- Called by the daily job without a signed-in user; the token is the check.
grant execute on function public.push_batch(uuid) to anon;
grant execute on function public.mark_notified(uuid, uuid[], date) to anon;
grant execute on function public.forget_subscription(uuid, text) to anon;

-- ---------------------------------------------------------------------------
-- Access
-- ---------------------------------------------------------------------------

alter table public.workout_plan enable row level security;
alter table public.workout_logs enable row level security;
alter table public.meals enable row level security;
alter table public.meal_plan enable row level security;
alter table public.push_subscriptions enable row level security;

do $$
declare
  t text;
begin
  foreach t in array array['workout_plan', 'workout_logs', 'meals', 'meal_plan', 'push_subscriptions'] loop
    execute format(
      'create policy "Own rows" on public.%I for all to authenticated
         using (user_id = (select auth.uid()))
         with check (user_id = (select auth.uid()))',
      t
    );
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
  end loop;
end;
$$;
